import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {startServer} from '../scripts/serve.mjs';
const server=await startServer();let browser;let count=0;
const check=(actual,expected,label)=>{assert.deepEqual(actual,expected,label);count++;};
try{
  browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
  const page=await browser.newPage({viewport:{width:1360,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.waitForFunction(()=>document.documentElement.dataset.ready==='true');
  const original=await page.locator('#source').inputValue();
  await page.locator('#set').click();
  const preview=await page.locator('#result').textContent();
  check(preview,original.replace('"moon test"','"moon test --target wasm-gc"'),'local replacement');
  check(await page.locator('#source').inputValue(),original,'preview leaves original alone');
  check(preview.includes('9007199254740993'),true,'exact identifier');
  await page.locator('#adopt').click();check(await page.locator('#source').inputValue(),preview,'adoption');
  await page.locator('[data-preset="settings"]').click();await page.locator('summary').click();await page.locator('#transaction').click();
  check((await page.locator('#result').textContent()).includes('/* Keep this explanation in the file. */'),true,'transaction comment preservation');
  check(await page.locator('#status').evaluate(e=>e.classList.contains('error')),false,'settings transaction valid');
  await page.locator('[data-preset="deployment"]').click();
  const deployment=await page.locator('#source').inputValue();
  await page.locator('#operations').fill(JSON.stringify([{op:'set',path:['version'],value:'4'},{op:'test',path:['version'],value:'3'}]));
  await page.locator('#transaction').click();check(await page.locator('#status').evaluate(e=>e.classList.contains('error')),true,'conflict visible');
  check(await page.locator('#source').inputValue(),deployment,'failed transaction leaves input');
  check(await page.locator('#adopt').isDisabled(),true,'cannot adopt failed result');
  await page.locator('#source').fill('{"a":}');await page.locator('#format').click();
  check(await page.locator('#status').evaluate(e=>e.classList.contains('error')),true,'invalid source refused');
  await page.locator('[data-preset="package"]').click();await page.locator('#format').click();
  await page.locator('#source').fill('{}');check(await page.locator('#adopt').isDisabled(),true,'preview invalidated on edits');
  await page.locator('[data-preset="package"]').click();await page.locator('#set').click();
  const download=page.waitForEvent('download');await page.locator('#download').click();check((await download).suggestedFilename(),'package.jsonc','download name');
  check(errors,[],'no page errors');
  await mkdir(new URL('../dist/',import.meta.url),{recursive:true});
  await page.screenshot({path:new URL('../dist/workbench-desktop.png',import.meta.url).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'mobile no overflow');
  await writeFile(new URL('../dist/browser-results.json',import.meta.url),JSON.stringify({checks:count,passed:count,engine:'chromium'},null,2));
  console.log(`Browser acceptance: ${count} checks passed.`);
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
